// Generates the app's copies of the design system styles.
// tokens.css: one :root custom property per token in design/system/project/tokens.json.
// psl-bundle.css: components/bundle.css without the Google Fonts @import (fonts are
// self-hosted) and without the preview-only helpers at the end of the file.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const designDir = join(here, '..', '..', 'design', 'system', 'project');
const stylesDir = join(here, '..', 'src', 'styles');

const PREVIEW_MARKER = '/* ---------- preview-only layout helpers';

export function buildTokensCss(tokens) {
  const lines = [];
  for (const group of ['color', 'spacing', 'radius', 'stroke', 'size', 'shadow', 'breakpoint']) {
    for (const token of tokens[group].tokens) lines.push(`  --${token.name}: ${token.value};`);
  }
  for (const [name, value] of Object.entries(tokens.type.families)) lines.push(`  --font-${name}: ${value};`);
  return (
    '/* Generated by scripts/gen-styles.mjs from design/system/project/tokens.json. Do not edit. */\n' +
    `:root {\n${lines.join('\n')}\n}\n`
  );
}

export function buildBundleCss(bundle) {
  const firstNewline = bundle.indexOf('\n');
  if (!bundle.slice(0, firstNewline).startsWith("@import url('https://fonts.googleapis.com/")) {
    throw new Error('bundle.css line 1 is not the Google Fonts @import');
  }
  const cut = bundle.indexOf(PREVIEW_MARKER);
  if (cut < 0) throw new Error('bundle.css has no preview-only helpers marker');
  return bundle.slice(firstNewline + 1, cut);
}

export function readDesignSources() {
  return {
    tokens: JSON.parse(readFileSync(join(designDir, 'tokens.json'), 'utf8')),
    bundle: readFileSync(join(designDir, 'components', 'bundle.css'), 'utf8'),
  };
}

export const outputPaths = {
  tokens: join(stylesDir, 'tokens.css'),
  bundle: join(stylesDir, 'psl-bundle.css'),
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { tokens, bundle } = readDesignSources();
  writeFileSync(outputPaths.tokens, buildTokensCss(tokens));
  writeFileSync(outputPaths.bundle, buildBundleCss(bundle));
  console.log(`wrote ${outputPaths.tokens}\nwrote ${outputPaths.bundle}`);
}
